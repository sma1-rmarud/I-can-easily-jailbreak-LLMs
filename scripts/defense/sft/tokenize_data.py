#!/usr/bin/env python3
"""
Tokenize JSONL chat data into NumpyPackedFSL format for OLMo-core SFT.

Each input JSONL file must contain lines with a "messages" field (list of
{role, content} dicts).  Assistant turns are masked for loss; system/user
turns are not.

Outputs (in --output_dir):
  token_ids_part_0.npy  — uint32, flat concatenation of all token-ID sequences
  labels_mask_0.npy     — uint8,  1 = compute loss, 0 = context
  tokenizer/            — tokenizer snapshot (used by training script)

Usage:
  python tokenize_data.py \\
      --inputs data/safety_original.jsonl data/general_sft.jsonl \\
      --output_dir data/tokenized/model_original \\
      --max_seq_length 4096
"""

import argparse
import hashlib
import json
import random
from pathlib import Path


def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument("--inputs", nargs="+", required=True, help="Input JSONL file(s)")
    p.add_argument("--output_dir", required=True)
    p.add_argument("--tokenizer", default="allenai/Olmo-3-7B-Instruct-SFT")
    p.add_argument("--max_seq_length", type=int, default=4096)
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--revision", default=None)
    p.add_argument("--empty-target-policy", choices=["keep", "error"], default="keep",
                   help="Keep fully masked truncated documents as in the archived recipe, or fail.")
    return p.parse_args()


def load_jsonl(path):
    with open(path) as f:
        return [json.loads(line) for line in f if line.strip()]


def tokenize_conversation(messages, tokenizer, max_length, eos_token_id, allow_empty_target=False):
    """
    Returns (token_ids: list[int], label_mask: list[int]).

    Label mask is 1 for assistant response tokens after the generation header,
    including template end-of-turn tokens, and 0 for system/user context.
    """
    if max_length < 2 or eos_token_id is None:
        raise ValueError("A sequence length >= 2 and an EOS token are required")
    # return_dict=False — transformers 5.x 는 기본적으로 BatchEncoding(dict)을
    # 반환하므로, 토큰 ID 리스트를 직접 받으려면 명시해야 한다 (4.x 와도 호환).
    full_tokens = tokenizer.apply_chat_template(
        messages, tokenize=True, add_generation_prompt=False, return_dict=False
    )
    label_mask = [0] * len(full_tokens)

    for i, msg in enumerate(messages):
        if msg["role"] != "assistant":
            continue
        # Tokens generated by the template UP TO but not including this turn,
        # with the generation prompt appended so the role header is not a target.
        prefix = tokenizer.apply_chat_template(
            messages[:i], tokenize=True, add_generation_prompt=True, return_dict=False
        )
        # Tokens through the end of this assistant turn.
        through = tokenizer.apply_chat_template(
            messages[:i + 1], tokenize=True, add_generation_prompt=False, return_dict=False
        )
        for j in range(len(prefix), min(len(through), len(label_mask))):
            label_mask[j] = 1

    # Ensure document ends with EOS (required for NumpyPackedFSL boundary detection)
    if full_tokens and full_tokens[-1] != eos_token_id:
        full_tokens.append(eos_token_id)
        label_mask.append(0)

    # Truncation must preserve a document boundary for the packed dataset.
    # A synthetic EOS is context only, not a target that teaches early stopping.
    full_tokens = full_tokens[:max_length]
    label_mask = label_mask[:max_length]
    if full_tokens and full_tokens[-1] != eos_token_id:
        full_tokens[-1] = eos_token_id
        label_mask[-1] = 0
    if not allow_empty_target and not any(label_mask[1:]):
        raise ValueError("No assistant target survives truncation; inspect the example and sequence length")
    return full_tokens, label_mask


def main():
    import numpy as np
    from tqdm import tqdm
    from transformers import AutoTokenizer

    args = parse_args()
    out_dir = Path(args.output_dir)
    if out_dir.exists() and any(out_dir.iterdir()):
        raise FileExistsError(f"Use an empty tokenization directory: {out_dir}")
    out_dir.mkdir(parents=True, exist_ok=True)

    tokenizer = AutoTokenizer.from_pretrained(args.tokenizer, revision=args.revision)
    eos_id = tokenizer.eos_token_id

    # Load + shuffle all examples
    examples = []
    for path in args.inputs:
        data = load_jsonl(path)
        examples.extend(data)
        print(f"  Loaded {len(data):,} examples from {path}")

    random.Random(args.seed).shuffle(examples)
    print(f"Total examples: {len(examples):,}")

    all_token_ids: list[int] = []
    all_label_masks: list[int] = []
    skipped = 0
    empty_target_examples = []

    for index, ex in enumerate(tqdm(examples, desc="Tokenizing")):
        raw_msgs = ex.get("messages", [])
        if not raw_msgs:
            skipped += 1
            continue

        msgs = [
            {"role": m["role"], "content": m["content"]}
            for m in raw_msgs
            if m.get("role") in ("system", "user", "assistant") and m.get("content") is not None
        ]

        if not any(m["role"] == "assistant" for m in msgs):
            skipped += 1
            continue

        try:
            token_ids, label_mask = tokenize_conversation(
                msgs, tokenizer, args.max_seq_length, eos_id,
                allow_empty_target=args.empty_target_policy == "keep",
            )
        except Exception as e:
            raise ValueError(f"Tokenization failed at shuffled example {index}: {e}") from e

        if not any(label_mask[1:]):
            empty_target_examples.append({
                "shuffled_index": index,
                "example_sha256": hashlib.sha256(json.dumps(ex, sort_keys=True).encode()).hexdigest(),
            })

        all_token_ids.extend(token_ids)
        all_label_masks.extend(label_mask)

    print(f"Skipped: {skipped:,}  |  Total tokens: {len(all_token_ids):,}")
    if empty_target_examples:
        print(f"Kept {len(empty_target_examples)} fully masked documents after truncation; "
              "they contribute no targets. See tokenization_manifest.json.")
    if skipped or not all_token_ids or not any(all_label_masks):
        raise ValueError(f"Invalid tokenization: skipped={skipped}, tokens={len(all_token_ids)}")

    token_arr = np.array(all_token_ids, dtype=np.uint32)
    mask_arr = np.array(all_label_masks, dtype=np.uint8)

    # OLMo-core 는 np.memmap 으로 이 파일들을 raw binary 로 읽는다.
    # np.save 의 헤더 (~128B, 공백 padding 포함) 는 데이터로 오해되므로
    # ndarray.tofile() 로 헤더 없이 기록한다. 확장자는 관습상 .npy 유지.
    token_path = out_dir / "token_ids_part_0.npy"
    mask_path = out_dir / "labels_mask_0.npy"
    token_arr.tofile(token_path)
    mask_arr.tofile(mask_path)

    frac_loss = mask_arr.mean() * 100
    print(f"Saved {token_path}  ({token_arr.nbytes / 1e6:.1f} MB)")
    print(f"Saved {mask_path}  ({mask_arr.nbytes / 1e6:.1f} MB)  loss-fraction={frac_loss:.1f}%")

    # Save tokenizer snapshot alongside the data for the training script
    tok_dir = out_dir / "tokenizer"
    tokenizer.save_pretrained(str(tok_dir))
    (out_dir / "tokenization_manifest.json").write_text(json.dumps({
        "inputs": {p: hashlib.sha256(Path(p).read_bytes()).hexdigest() for p in args.inputs},
        "tokenizer": args.tokenizer, "revision": args.revision, "seed": args.seed,
        "max_seq_length": args.max_seq_length, "examples": len(examples),
        "truncation": "preserve_eos_mask_synthetic_boundary",
        "tokens": len(all_token_ids), "loss_tokens": sum(all_label_masks),
        "empty_target_policy": args.empty_target_policy,
        "empty_target_examples": empty_target_examples,
    }, indent=2) + "\n")
    print(f"Saved tokenizer → {tok_dir}")


if __name__ == "__main__":
    main()
